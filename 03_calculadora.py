#calculadora

num1=input("introduce el primer numero: ")
num2=input("introduce el segundo numero: ")

#convertir textos en numeros, puede ser int o float 
num1=float(num1)
num2=int(num2)

print(f"la suma de {num1} y {num2} es {num1+num2} ")
print(f"la resta de {num1} y {num2} es {num1-num2} ")
print(f"la multiplicación de {num1} y {num2} es {num1*num2} ")
print(f"la potencia de {num1} y {num2} es {num1**num2} ")
print(f"la divición de {num1} y {num2} es {num1/num2} ")

